/**
 * Bundle the exported panel's runtime into one file.
 *
 * An exported panel is a single HTML page carrying the screen, the ladder
 * program and everything needed to run them. That last part is this: React,
 * the scan engine, the widget renderer and the alarm state machine, in one
 * script the export inlines.
 *
 * Bundled ahead of time rather than at export, because the alternative is
 * shipping a bundler to the browser. It is written into the calling app's
 * `public/`, so the editor fetches it from its own origin at export time; the
 * exported file itself fetches nothing, which is the whole point of it.
 *
 * It lives beside the panel entry it bundles rather than in one of the apps,
 * because both the web app and the desktop app need it. When it lived in
 * apps/web the desktop shipped without it, and the export menu item there
 * failed on a 404 for a file nobody had noticed was missing.
 *
 * IIFE rather than an ES module: an exported panel is opened from a file://
 * URL as often as from a server, and a module script there is blocked by the
 * same origin rules with an error that reads like the file is corrupt.
 */

import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const entry = resolve(here, "../src/panel/main.tsx");

// Where it goes is the caller's business: each app serves it from its own
// public directory, and the editor fetches it from its own origin.
const flag = process.argv.indexOf("--out");
if (flag === -1 || !process.argv[flag + 1]) {
  console.error("build-panel-runtime: --out <public dir> is required");
  process.exit(1);
}
const out = resolve(process.cwd(), process.argv[flag + 1], "panel/runtime.js");

await mkdir(dirname(out), { recursive: true });

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  minify: true,
  // The panel runs on whatever browser the machine on the plant floor has,
  // which is not always a recent one. Targeting a few years back costs a
  // little size and removes a class of "it works on my laptop".
  target: ["es2020", "chrome90", "firefox90", "safari15"],
  jsx: "automatic",
  // React reads this to decide whether to ship its development warnings. Left
  // unset it throws "process is not defined" the moment the page loads.
  define: { "process.env.NODE_ENV": '"production"' },
  outfile: out,
  legalComments: "none",
  logLevel: "warning",
  metafile: true,
  // The renderer draws with inline styles and the shell does too, so there is
  // no stylesheet to emit. If that ever stops being true this will start
  // producing a CSS file, and the export has to inline it as well.
  loader: { ".css": "empty" },
});

if (result.errors.length > 0) process.exit(1);

/*
 * Nothing but the one file.
 *
 * A stylesheet appearing here means something in the panel's import graph
 * started pulling in a component that needs one, and the export inlines only
 * the script: the panel would ship looking subtly wrong with no error anywhere.
 * The same goes for a second chunk. Fail the build instead.
 */
const extra = Object.keys(result.metafile?.outputs ?? {}).filter((f) => !f.endsWith("runtime.js"));
if (extra.length > 0) {
  console.error(
    `The panel bundle produced files the export cannot carry: ${extra.join(", ")}.
Something under packages/hmi/src/panel now imports a stylesheet or a second chunk.`,
  );
  process.exit(1);
}

/*
 * The panel must not be able to reach the network.
 *
 * This is the same promise the desktop app makes and the same one the page
 * makes about an exported panel: it runs from a USB stick on a machine that
 * has never been online. A promise like that is worth exactly as much as the
 * check behind it, and the way it would break is nobody's fault and nobody's
 * notice: an import added for a good reason that happens to pull in something
 * which phones home.
 *
 * Checked against the built bundle rather than the sources, because the
 * sources are not what ships.
 */
const bundle = await readFile(out, "utf8");
const forbidden = [
  [/\bfetch\s*\(/, "fetch"],
  [/\bXMLHttpRequest\b/, "XMLHttpRequest"],
  [/\bnew\s+WebSocket\b/, "WebSocket"],
  [/\bnavigator\.sendBeacon\b/, "sendBeacon"],
  [/\bEventSource\b/, "EventSource"],
  [/\bimport\s*\(/, "a dynamic import"],
];
const found = forbidden.filter(([re]) => re.test(bundle)).map(([, name]) => name);
if (found.length > 0) {
  console.error(
    `The panel runtime can reach the network: it contains ${found.join(", ")}.
An exported panel has to run with no network at all. Find the import that
brought this in and keep it out of packages/hmi/src/panel.`,
  );
  process.exit(1);
}

const { size } = await stat(out);
await writeFile(
  resolve(dirname(out), "README.txt"),
  [
    "runtime.js is generated by apps/web/scripts/build-panel-runtime.mjs.",
    "Do not edit it. Run `pnpm panel:build` after changing anything under",
    "packages/hmi/src/panel, or the exported panels will run the old code.",
    "",
  ].join("\n"),
);

console.log(`panel runtime: ${(size / 1024).toFixed(0)} kB at ${out}`);
